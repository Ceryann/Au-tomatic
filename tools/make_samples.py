"""Build SYNTHETIC sample outputs for the README (no real prices, no Twelve Data content).

The data is a random walk generated by the test helpers, so the levels mean nothing; every
output carries a visible "synthetic" banner. Usage:

    python tools/make_samples.py            # writes docs/samples/*.html (+ PNG if wkhtmltoimage exists)
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

import yaml  # noqa: E402

from src.data_fetcher import get_gold_bundle  # noqa: E402
from src.email_dispatcher import build_forecast_email  # noqa: E402
from src.quant_engine import forecast_day  # noqa: E402
from src.report import build_report  # noqa: E402
from test_data_layer import NOW, FakeTD, hourly_until  # noqa: E402

BANNER = ("SYNTHETIC SAMPLE: generated from a random walk, not market data. "
          "The levels below mean nothing and must not be used for trading.")


def _shrink(png: Path, max_height: int | None) -> None:
    """Keep README images light: crop very tall pages and palette-compress (needs Pillow; optional)."""
    try:
        from PIL import Image
    except ImportError:
        return
    im = Image.open(png).convert("RGB")
    if max_height and im.height > max_height:
        im = im.crop((0, 0, im.width, max_height))
    im.quantize(colors=128, method=Image.Quantize.MEDIANCUT).save(png, optimize=True)


def main() -> int:
    cfg = yaml.safe_load((ROOT / "config.yaml").read_text(encoding="utf-8"))
    hourly = hourly_until(NOW)
    with FakeTD(hourly):
        bundle = get_gold_bundle(cfg, now_utc=NOW)
    fc = forecast_day(bundle, None, cfg, event_today=False, explain=True)
    _, email_html, _ = build_forecast_email(bundle, fc, cfg)
    rep_html, _ = build_report(bundle, fc, cfg)

    out = ROOT / "docs" / "samples"
    out.mkdir(parents=True, exist_ok=True)
    banner = f'<div style="background:#fff3cd;color:#664d03;padding:8px 12px;font:600 13px sans-serif">{BANNER}</div>'
    pages = {"email_sample": (email_html, 520), "report_sample": (rep_html, 980)}
    for name, (html, width) in pages.items():
        html = html.replace("<body>", "<body>" + banner, 1) if "<body>" in html else banner + html
        if "charset" not in html[:2000].lower():      # emails carry UTF-8 in MIME headers; files need a meta tag
            html = '<meta charset="utf-8">' + html
        path = out / f"{name}.html"
        path.write_text(html, encoding="utf-8")
        exe = shutil.which("wkhtmltoimage")
        if exe:
            png = ROOT / "docs" / "img" / f"{name}.png"
            subprocess.run([exe, "--quiet", "--width", str(width), "--enable-local-file-access", str(path), str(png)],
                           check=False)
            _shrink(png, max_height=2400 if name == "report_sample" else None)
            print("wrote", png.relative_to(ROOT))
        print("wrote", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
